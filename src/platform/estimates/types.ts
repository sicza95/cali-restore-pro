export type AreaUnit = 'm²' | 'cm²' | 'ft²' | 'in²';
export type Measurement = {
  version: 1;
  project: string;
  object: string;
  surface: string;
  phase: string;
  scope: string;
  revision: string;
  calibration: string | null;
  assessment?: string;
  source: 'fixture' | 'committed';
  validity: 'valid' | 'missing' | 'stale' | 'computing' | 'failed';
  area: string | null;
  unit: AreaUnit;
};
export type PresetReference = { id: string; version: number };
export type Phase = {
  id: string;
  name: string;
  archived: boolean;
  surface: string;
  scope: string;
  scopeSource?: string;
  assessment?: string;
  measurement: 'missing' | 'stale' | 'ready';
  quantity?: Measurement;
  mode: 'time' | 'productivity';
  time: string;
  productivity: Partial<Record<AreaUnit, string>>;
  multiplier: string;
  factorDraft?: string;
  price: 'hourly' | 'fixed' | 'area';
  rate: Partial<Record<string, string>>;
  material: string;
  units: AreaUnit;
  presets?: PresetReference[];
};
export type Extra = {
  id: string;
  name: string;
  object: string;
  method: 'fixed' | 'hourly';
  hours: string;
  rate: Partial<Record<string, string>>;
  included: boolean;
};
export type Adjustment = { id: string; name: string; percent: string };
export type EstimateInput = {
  schema: 1;
  project: string;
  revision: number;
  currency: string;
  priceCurrency: string;
  objects: { id: string; name: string; surfaces: string[] }[];
  selected: string[];
  phases: Phase[];
  extras: Extra[];
  adjustments: Adjustment[];
  tax: { enabled: boolean; rate: string };
  assumptions: string;
};
export type PhaseResult = {
  id: string;
  hours: string | null;
  productivity: string | null;
  baseline: string | null;
  work: string | null;
  material: string;
  subtotal: string | null;
  issues: string[];
};
export type EstimateResult = {
  calculation: 'restoration-v1';
  rounding: 'half-away-from-zero';
  precision: number;
  complete: boolean;
  illustrative: boolean;
  phases: PhaseResult[];
  objects: { id: string; name: string; subtotal: string | null }[];
  extras: string;
  adjustments: { id: string; amount: string }[];
  hours: string | null;
  subtotal: string | null;
  beforeTax: string | null;
  taxTotal: string | null;
  total: string | null;
  issues: string[];
};
export type EstimateSnapshot = {
  schema: 1;
  id: string;
  version: number;
  createdAt: string;
  issued: boolean;
  input: EstimateInput;
  result: EstimateResult;
};
export type EstimateDocument = { schema: 1; draft: EstimateInput; snapshots: EstimateSnapshot[] };
export type Preset = {
  id: string;
  version: number;
  name: string;
  kind: 'rate' | 'productivity';
  value: string;
  unit: 'hourly' | 'fixed' | AreaUnit;
  currency: string | null;
  archived: boolean;
};
