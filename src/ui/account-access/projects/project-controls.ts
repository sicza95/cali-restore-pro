import type { ControlContract } from '../../control-registry/types';

function control(
  id: string,
  labelKey: string,
  command: string,
  composition: string,
  owner: ControlContract['owner'],
  valueSource: string,
  permission = 'Signed-in account and unlocked local vault',
  prerequisite = 'Accessible project scope',
): ControlContract {
  return {
    id,
    labelKey,
    helpKey: 'missing',
    command,
    composition,
    owner,
    valueSource,
    permission,
    prerequisite,
    behavior: 'functional',
    unavailable: {
      failure: 'Show the relevant command or access error and preserve the last durable state.',
      empty: 'Omit the action when its target is absent.',
      locked: 'Hide project controls and require vault unlock.',
    },
  };
}

